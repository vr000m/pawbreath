// Deterministic release metadata: rerun after editing any deployed file.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const dist = new URL('dist/', root);
const { version } = JSON.parse(readFileSync(new URL('package.json', root)));
if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error('Use a major.minor.patch package version.');
const lock = JSON.parse(readFileSync(new URL('package-lock.json', root)));
if (lock.version !== version || lock.packages[''].version !== version) throw new Error('Package and lockfile versions differ.');
const workerUrl = new URL('sw.js', dist);
const worker = readFileSync(workerUrl, 'utf8');
const marker = /^const RELEASE = .*; \/\/ Generated by scripts\/release.mjs$/m;
if (!marker.test(worker)) throw new Error('Worker release marker missing.');
const hash = createHash('sha256').update(version + '\n');
for (const name of readdirSync(dist).sort()) {
  if (['version.mjs', 'release.json'].includes(name)) continue;
  const bytes = name === 'sw.js' ? worker.replace(marker, 'const RELEASE = null; // Generated by scripts/release.mjs')
    : readFileSync(new URL(name, dist));
  hash.update(name + '\0').update(bytes).update('\0');
}
const release = JSON.stringify({ version, build: hash.digest('hex').slice(0, 12) });
const generated = new Map([
  ['version.mjs', `// Generated by scripts/release.mjs. Do not edit.\nexport const RELEASE = Object.freeze(${release});\n`],
  ['release.json', release + '\n'],
  ['sw.js', worker.replace(marker, `const RELEASE = ${release}; // Generated by scripts/release.mjs`)],
]);
for (const [name, content] of generated) {
  const file = new URL(name, dist);
  if (process.argv.includes('--check')) {
    let actual;
    try { actual = readFileSync(file, 'utf8'); } catch { /* Report missing generated metadata below. */ }
    if (actual !== content) throw new Error(`${name} is stale. Run npm run release and commit the generated files.`);
  } else writeFileSync(file, content);
}
console.log(`Pawbreath ${version} · ${JSON.parse(release).build}${process.argv.includes('--check') ? ' verified' : ''}`);
