import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, mkdtempSync, mkdirSync, writeFileSync, copyFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { createUpdateMonitor, validRelease } from '../dist/updates.mjs';
import { RELEASE } from '../dist/version.mjs';

const nextRelease = { version: '1.2.0', build: 'abcdef123456' };
function setup({ connected = true, persisted = null, unsupported = false, controlled = true } = {}) {
  // Per the service worker spec, a failed first installation leaves a registration with no worker and
  // removes it, so the next register() yields a new ServiceWorkerRegistration. A registration that still
  // holds a worker is returned as is.
  function makeRegistration() {
    const created = new EventTarget();
    created.active = {};
    created.waiting = null;
    created.installing = null;
    created.updatefoundListeners = 0;
    const add = created.addEventListener.bind(created);
    created.addEventListener = (type, ...args) => { if (type === 'updatefound') created.updatefoundListeners++; add(type, ...args); };
    // update() rejects when the registration has no worker at all.
    created.update = async () => {
      if (!created.installing && !created.waiting && !created.active) {
        throw new DOMException('No worker', 'InvalidStateError');
      }
    };
    return created;
  }
  let registration = makeRegistration();
  const serviceWorker = new EventTarget();
  serviceWorker.controller = controlled ? {} : null;
  let registrations = 0;
  serviceWorker.register = async (url, options) => {
    assert.equal(url, './sw.js');
    assert.equal(options.updateViaCache, 'none');
    if (registrations > 0 && !registration.installing && !registration.waiting && !registration.active) {
      registration = makeRegistration();
      registration.active = null;
    }
    registrations++;
    return registration;
  };
  serviceWorker.getRegistration = async () => registration;
  let published = RELEASE;
  let failure = false;
  let fetches = 0;
  let gate = null;
  let latestState;
  const monitor = createUpdateMonitor({
    serviceWorker: unsupported ? null : serviceWorker,
    online: () => connected,
    getRelease: async () => { fetches++; if (gate) await gate; if (failure) throw new Error('Network failed'); return published; },
    now: () => '2026-11-13T20:00:00.000Z',
    storage: { getItem: () => persisted, setItem: (_, value) => { persisted = value; } },
    onChange: value => { latestState = value; },
  });
  return { monitor, get registration() { return registration; }, serviceWorker,
    get state() { return latestState; }, get registrations() { return registrations; },
    get fetches() { return fetches; }, get persisted() { return persisted; },
    connect(value) { connected = value; monitor.refresh(); },
    publish(value) { published = value; }, fail(value = true) { failure = value; },
    holdRelease() { let open; gate = new Promise(resolve => { open = resolve; }); return () => { gate = null; open(); }; },
  };
}

test('release identity is shared by package, displayed app, published metadata and offline cache', () => {
  const read = name => readFileSync(new URL('../' + name, import.meta.url), 'utf8');
  assert.equal(RELEASE.version, JSON.parse(read('package.json')).version);
  assert.deepEqual(RELEASE, JSON.parse(read('dist/release.json')));
  assert.ok(read('dist/sw.js').includes(JSON.stringify(RELEASE)));
  assert.ok(validRelease(RELEASE));
  assert.ok(!validRelease({ version: 'Sign in', build: RELEASE.build }));
  // Coercible non-strings must not pass, and the result is a real boolean.
  assert.equal(validRelease({ version: ['1.1.0'], build: [RELEASE.build] }), false);
  assert.equal(validRelease(null), false);
  assert.equal(validRelease(RELEASE), true);
});

test('release generation is deterministic and rejects stale metadata after a source edit', () => {
  const dir = mkdtempSync(join(tmpdir(), 'pawbreath-release-'));
  try {
    mkdirSync(join(dir, 'scripts/lib'), { recursive: true }); mkdirSync(join(dir, 'dist'));
    copyFileSync(new URL('../scripts/release.mjs', import.meta.url), join(dir, 'scripts/release.mjs'));
    copyFileSync(new URL('../scripts/lib/precache-assets.mjs', import.meta.url), join(dir, 'scripts/lib/precache-assets.mjs'));
    writeFileSync(join(dir, 'package.json'), JSON.stringify({ version: '1.1.0' }));
    writeFileSync(join(dir, 'package-lock.json'), JSON.stringify({ version: '1.1.0', packages: { '': { version: '1.1.0' } } }));
    const workerTemplate = 'const RELEASE = null; // Generated by scripts/release.mjs\n' +
      'const DIGESTS = null; // Generated by scripts/release.mjs\n' + "const ASSETS = ['./', './version.mjs'];\n";
    writeFileSync(join(dir, 'dist/sw.js'), workerTemplate);
    writeFileSync(join(dir, 'dist/index.html'), 'first app');
    const run = (...args) => spawnSync(process.execPath, [join(dir, 'scripts/release.mjs'), ...args], { encoding: 'utf8' });
    const digests = () => JSON.parse(readFileSync(join(dir, 'dist/sw.js'), 'utf8').match(/^const DIGESTS = (.*); \/\/ Generated/m)[1]);
    const sha = text => createHash('sha256').update(text).digest('hex');
    assert.equal(run().status, 0);
    const first = readFileSync(join(dir, 'dist/release.json'), 'utf8');
    assert.equal(run('--check').status, 0);
    // The digest manifest describes the deployed shell, including version.mjs as generated for this build.
    assert.deepEqual(digests(), { './': sha('first app'), './version.mjs': sha(readFileSync(join(dir, 'dist/version.mjs'))) });
    // The generated digest line is not an input to the build ID; otherwise the version.mjs digest would be circular.
    writeFileSync(join(dir, 'dist/sw.js'), workerTemplate);
    assert.equal(run().status, 0);
    assert.equal(readFileSync(join(dir, 'dist/release.json'), 'utf8'), first);
    // Files and directories that are never deployed must not alter or invalidate the build ID.
    writeFileSync(join(dir, 'dist/.DS_Store'), 'finder state');
    mkdirSync(join(dir, 'dist/empty'));
    assert.equal(run('--check').status, 0);
    assert.equal(run().status, 0);
    assert.equal(readFileSync(join(dir, 'dist/release.json'), 'utf8'), first);
    writeFileSync(join(dir, 'dist/index.html'), 'changed app');
    assert.notEqual(run('--check').status, 0);
    assert.equal(run().status, 0);
    assert.notEqual(readFileSync(join(dir, 'dist/release.json'), 'utf8'), first);
    assert.equal(run('--check').status, 0);
    assert.equal(digests()['./'], sha('changed app'));
    writeFileSync(join(dir, 'dist/sw.js'), 'const RELEASE = null; // Generated by scripts/release.mjs\n');
    assert.match(run().stderr, /digest marker missing/);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('successful online check compares exact build and persists its timestamp', async () => {
  const app = setup();
  await app.monitor.check();
  assert.match(app.state.message, /latest published version/);
  assert.equal(app.state.offlineReady, true);
  assert.equal(app.persisted, '2026-11-13T20:00:00.000Z');
  app.publish({ ...RELEASE, build: '000000000000' });
  await app.monitor.check();
  assert.match(app.state.message, /download is not ready/);
});

test('download and waiting states cannot claim the old client is current or activate an update', async () => {
  const app = setup();
  await app.monitor.check();
  const worker = new EventTarget();
  // Any accidental activation request fails this test.
  worker.postMessage = () => assert.fail('Must not force update activation');
  app.registration.installing = worker;
  app.registration.dispatchEvent(new Event('updatefound'));
  assert.match(app.state.message, /Downloading/);
  app.publish(nextRelease);
  await app.monitor.check();
  app.registration.installing = null;
  app.registration.waiting = worker;
  worker.state = 'installed';
  worker.dispatchEvent(new Event('statechange'));
  assert.match(app.state.message, /Update ready/);
  assert.deepEqual(app.state.running, RELEASE);
  assert.deepEqual(app.state.latest, nextRelease);
  app.connect(false);
  assert.match(app.state.message, /downloaded update can be used offline/);
});

test('offline launch finds a downloaded waiting update without contacting the server', async () => {
  const app = setup({ connected: false, persisted: '2026-11-12T20:00:00.000Z' });
  app.registration.waiting = {};
  await app.monitor.check();
  assert.equal(app.fetches, 0);
  assert.equal(app.registrations, 0);
  assert.match(app.state.message, /Update ready/);
  assert.equal(app.state.checked, '2026-11-12T20:00:00.000Z');
  assert.equal(app.state.offlineReady, true);
});

test('failed checks and installs do not report current or replace the last successful check', async () => {
  const app = setup();
  await app.monitor.check();
  app.fail();
  await app.monitor.check();
  assert.match(app.state.message, /Could not complete/);
  assert.equal(app.state.checked, app.persisted);
  const worker = new EventTarget();
  app.registration.installing = worker;
  app.registration.dispatchEvent(new Event('updatefound'));
  app.registration.installing = null;
  worker.state = 'redundant';
  worker.dispatchEvent(new Event('statechange'));
  assert.match(app.state.message, /Could not complete/);
  assert.equal(app.state.offlineReady, true);
});

test('an activated replacement asks for a safe reopen without reloading the running client', async () => {
  const app = setup();
  await app.monitor.check();
  app.serviceWorker.dispatchEvent(new Event('controllerchange'));
  assert.equal(app.state.activationChanged, true);
  assert.match(app.state.message, /Save your work/);
  assert.deepEqual(app.state.running, RELEASE);
});

// Build B finishing its first installation claims this page while release.json is still in flight.
async function claimBeforeMetadata(release) {
  const app = setup({ controlled: false });
  app.publish(release);
  const open = app.holdRelease();
  const pending = app.monitor.check();
  await new Promise(resolve => setTimeout(resolve, 0));
  assert.equal(app.fetches, 1);
  app.serviceWorker.dispatchEvent(new Event('controllerchange'));
  assert.equal(app.state.activationChanged, false, 'nothing is known about the published release yet');
  open();
  await pending;
  return app;
}

test('a first installation that claims the page before release metadata arrives is reconciled when it does', async () => {
  const app = await claimBeforeMetadata(nextRelease);
  assert.equal(app.state.activationChanged, true);
  assert.match(app.state.message, /An update has activated/);
  assert.doesNotMatch(app.state.message, /not ready yet/);
});

test('a claim before metadata is not an update when the published release is the running one', async () => {
  const app = await claimBeforeMetadata(RELEASE);
  assert.equal(app.state.activationChanged, false);
  assert.match(app.state.message, /latest published version/);
});

test('a first installation with no newer release shows no update notice, and a failed check keeps the claim pending', async () => {
  const app = setup({ controlled: false });
  await app.monitor.check();
  app.serviceWorker.dispatchEvent(new Event('controllerchange'));
  assert.equal(app.state.activationChanged, false);
  assert.match(app.state.message, /latest published version/);
  // A claim seen while the release is unknown survives a failed check and resolves on the next good one.
  const failing = setup({ controlled: false });
  failing.fail();
  await failing.monitor.check();
  failing.serviceWorker.dispatchEvent(new Event('controllerchange'));
  assert.equal(failing.state.activationChanged, false);
  failing.fail(false);
  failing.publish(nextRelease);
  await failing.monitor.check();
  assert.equal(failing.state.activationChanged, true);
});

